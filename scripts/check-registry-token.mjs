import assert from "node:assert/strict";
import {verify,createPublicKey} from "node:crypto";
import {readFileSync} from "node:fs";
import {join} from "node:path";
const role=process.argv[2];
assert.ok(["reader","admin"].includes(role),"Specify reader or admin");
const token=readFileSync(0,"utf8").trim();
const parts=token.split(".");
assert.equal(parts.length,3,"Expected signed JWT");
const decode=s=>JSON.parse(Buffer.from(s,"base64url").toString("utf8"));
const header=decode(parts[0]), claims=decode(parts[1]);
assert.equal(header.alg,"RS256");
assert.equal(header.kid,"domislink-registry-staging");
const dir=process.env.DOMISLINK_SECRET_DIR;
assert.ok(dir,"Set DOMISLINK_SECRET_DIR");
const key=createPublicKey(readFileSync(join(dir,"OIDC_PUBLIC_KEY_PEM")));
assert.ok(verify("RSA-SHA256",Buffer.from(parts[0]+"."+parts[1]),key,Buffer.from(parts[2],"base64url")),"Invalid signature");
const now=Math.floor(Date.now()/1000);
assert.equal(claims.iss,"https://domislink-sso-registry-staging.amaechi-u.workers.dev");
assert.equal(claims.aud,"domislink-central-services-registry");
assert.ok(typeof claims.sub==="string" && claims.sub.length>0);
assert.ok(Number.isInteger(claims.exp)&&Number.isInteger(claims.nbf)&&Number.isInteger(claims.iat));
assert.ok(claims.exp>now&&claims.nbf<=now&&claims.iat<=now&&claims.exp-claims.nbf===900);
assert.ok(typeof claims.jti==="string"&&claims.jti.length>0);
assert.equal(claims.scope,role==="admin"?"services:read services:write":"services:read");
assert.deepEqual(claims.roles,role==="admin"?["domislink:services:admin"]:[]);
console.log("Registry JWT signature and "+role+" claims: PASS");
