import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {join} from "node:path";
const issuer="https://domislink-sso-registry-staging.amaechi-u.workers.dev";
const callback=process.argv[2];
assert.ok(callback,"Supply verified staging callback URL");
const url=new URL(callback);
assert.equal(url.protocol,"https:");
assert.ok(url.hostname.endsWith(".workers.dev") && url.hostname.includes("staging"),"Only staging Workers callbacks permitted");
assert.ok(!url.username&&!url.password&&!url.hash);
assert.ok(url.pathname!=="/");
assert.equal(process.argv[3],"--confirm-register","Explicit registration confirmation required");
const config=JSON.parse(readFileSync("wrangler.registry-staging.local.jsonc","utf8"));
assert.equal(config.vars.SSO_ISSUER,issuer);
assert.equal(config.vars.REGISTRY_OIDC_CLIENT_ID,"REPLACE_WITH_STAGING_CLIENT_ID","Existing client: do not register again");
const dir=process.env.DOMISLINK_SECRET_DIR;
assert.ok(dir,"Set DOMISLINK_SECRET_DIR");
const key=readFileSync(join(dir,"SSO_ADMIN_API_KEY"),"utf8").trim();
assert.match(key,/^[a-f0-9]{64}$/);
const response=await fetch(issuer+"/admin/clients",{method:"POST",redirect:"error",signal:AbortSignal.timeout(15000),headers:{Authorization:"Bearer "+key,"Content-Type":"application/json"},body:JSON.stringify({client_name:"DomisLink Registry Staging",redirect_uris:[callback],allowed_scopes:["openid","profile","email"]})});
assert.equal(response.status,201,"Registration failed; inspect existing clients before retrying");
const result=await response.json();
assert.match(result.client_id,/^dl_[A-Za-z0-9_-]+$/);
assert.deepEqual(result.redirect_uris,[callback]);
console.log("Registered client ID (not a secret): "+result.client_id);
console.log("Record this ID in the local staging configuration before any further registration.");
